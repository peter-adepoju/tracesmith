/**
 * Regenerate content/registry.ts from the MDX files on disk.
 *
 * Next needs static imports to bundle MDX, so the registry cannot be built at
 * runtime. Run this after adding a lesson:  npm run registry
 */
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const contentDir = fileURLToPath(new URL("../content", import.meta.url));

const weeks = (await readdir(contentDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^w\d{2}$/.test(entry.name))
  .map((entry) => entry.name)
  .sort();

const keys = [];
for (const week of weeks) {
  const days = (await readdir(join(contentDir, week)))
    .filter((name) => /^d\d{2}\.mdx$/.test(name))
    .sort();
  for (const day of days) {
    keys.push({ key: `${week}${day.replace(".mdx", "")}`, path: `./${week}/${day}` });
  }
}

const file = `import type { ComponentType } from "react";

// Generated by \`npm run registry\`. Edit lessons, not this file.
${keys.map((entry) => `import ${entry.key} from "${entry.path}";`).join("\n")}

export const LESSONS: Record<string, ComponentType> = {
${keys.map((entry) => `  ${entry.key},`).join("\n")}
};

export function hasLesson(key: string): boolean {
  return key in LESSONS;
}
`;

await writeFile(join(contentDir, "registry.ts"), file, "utf8");
console.log(`registry.ts written with ${keys.length} lessons`);
